	/// <summary>Emits the timestamp readers for both layouts.</summary>
	static void EmitTimestampMethods(CodeWriter body)
	{
		body.XmlSummary(
				"Reads the creation time of a value produced by NewGuid.",
				"Returns false for any other value, including an identifier created by a different generator or a",
				"timestamp outside the range a DateTimeOffset can represent."
			)
			.Method(
				new MethodDeclarationOptions("TryGetTimestamp", BooleanType(), TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					Parameters = [GuidParameter("value"), TimestampOutParameter()],
				},
				method =>
				{
					EmitReadTimestampFromBytes(method, 0);
					method.IfBlock(
						"(bytes[6] & 0xF0) != 0x70",
						rejected =>
						{
							rejected.Assignment("timestamp", "default");
							rejected.Return("false");
						}
					);
					EmitAcceptTimestamp(method);
				}
			);

		body.XmlSummary(
				"Reads the creation time of a value produced by NewSqlServerGuid.",
				"Returns false for any other value, including an identifier created by a different generator or a",
				"timestamp outside the range a DateTimeOffset can represent."
			)
			.Method(
				new MethodDeclarationOptions(
					"TryGetSqlServerTimestamp",
					BooleanType(),
					TypeDeclarationAccessibility.Public
				)
				{
					IsStatic = true,
					Parameters = [GuidParameter("value"), TimestampOutParameter()],
				},
				method =>
				{
					EmitReadTimestampFromBytes(method, 10);
					EmitAcceptTimestamp(method);
				}
			);
	}

	/// <summary>Emits the byte reads shared by both timestamp readers.</summary>
	static void EmitReadTimestampFromBytes(CodeWriter method, int offset)
	{
		method.Assignment("global::System.Span<byte>", "bytes", "stackalloc byte[16]");
		method.MethodCallOn("value", "TryWriteBytes", "bytes", "bigEndian: true", "out _");
		var bytes = string.Join(
			" | ",
			Enumerable
				.Range(0, 5)
				.Select(index => $"((long)bytes[{index + offset}] << {40 - (index * 8)})")
				.Append($"bytes[{offset + 5}]")
		);
		method.Assignment("var", "unixMilliseconds", bytes);
	}

	/// <summary>Emits the range check and the timestamp a reader assigns once the value is known good.</summary>
	static void EmitAcceptTimestamp(CodeWriter method)
	{
		method.IfBlock(
			"unixMilliseconds < 0L || unixMilliseconds > MaxUnixMilliseconds",
			rejected =>
			{
				rejected.Assignment("timestamp", "default");
				rejected.Return("false");
			}
		);
		method.Assignment("timestamp", "global::System.DateTimeOffset.FromUnixTimeMilliseconds(unixMilliseconds)");
		method.Return("true");
	}

