	static string SanitizeIdentifier(string typeName)
	{
		var name = typeName.StartsWith("global::", StringComparison.Ordinal)
			? typeName.Substring("global::".Length)
			: typeName;
		System.Text.StringBuilder builder = new(name.Length);
		foreach (var character in name)
			builder.Append(char.IsLetterOrDigit(character) ? character : '_');

		return builder.ToString();
	}

	static string UniqueName(string name, HashSet<string> usedNames)
	{
		var candidate = name;
		var suffix = 2;
		while (!usedNames.Add(candidate))
			candidate = $"{name}_{suffix++}";

		return candidate;
	}

