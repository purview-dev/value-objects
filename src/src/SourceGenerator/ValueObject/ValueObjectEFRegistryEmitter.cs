	/// <summary>Emits the random-byte fill both creators start from.</summary>
	static void EmitFillRandomBytes(CodeWriter method)
	{
		method.Assignment("global::System.Span<byte>", "bytes", "stackalloc byte[16]");
		method.MethodCallOn("global::System.Security.Cryptography.RandomNumberGenerator", "Fill", "bytes");
	}

	/// <summary>Emits the six big-endian timestamp bytes starting at <paramref name="offset"/>.</summary>
	static void EmitTimestampIntoBytes(CodeWriter method, int offset)
	{
		for (var index = 0; index < 5; index++)
			method.Assignment($"bytes[{index + offset}]", $"(byte)(unixMilliseconds >> {40 - (index * 8)})");

		method.Assignment($"bytes[{offset + 5}]", "(byte)unixMilliseconds");
	}

