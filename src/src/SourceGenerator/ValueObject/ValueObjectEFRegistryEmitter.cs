	/// <summary>Emits the UUIDv7 creators, from the current time and from an explicit creation time.</summary>
	static void EmitUuidV7GuidMethods(CodeWriter body)
	{
		body.XmlSummary("Creates a new version 7 identifier.")
			.MethodExpression(
				new MethodDeclarationOptions("NewGuid", GuidType(), TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					ExpressionBody = "NewGuid(global::System.DateTimeOffset.UtcNow)",
				}
			)
			.XmlSummary("Creates a version 7 identifier for the given creation time.")
			.Method(
				new MethodDeclarationOptions("NewGuid", GuidType(), TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					Parameters = [TimestampParameter()],
				},
				method =>
				{
					method.Assignment("var", "unixMilliseconds", "timestamp.ToUnixTimeMilliseconds()");
					EmitFillRandomBytes(method);
					EmitTimestampIntoBytes(method, 0);
					method.Assignment("bytes[6]", "(byte)((bytes[6] & 0x0F) | 0x70)");
					method.Assignment("bytes[8]", "(byte)((bytes[8] & 0x3F) | 0x80)");
					method.Return("new global::System.Guid(bytes, bigEndian: true)");
				}
			);
	}

